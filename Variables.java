public class Variables {
    public static void main(String[] args) {
        // This is a byte
        byte my_byte = 25;
        System.out.println(my_byte);
        // This is a short
        short my_short = 225;
        System.out.println(my_short);
        // This is an int
        int my_int = 2250;
        System.out.println(my_int);
        // This is a long
        long my_long = 22500L;
        System.out.println(my_long);
        // This is a char
        char my_char = 'A';
        System.out.println(my_char);
        // This is a boolean
        boolean my_boolean = true;
        System.out.println(my_boolean);
        // This is a float
        float my_float = 22.5f;
        System.out.println(my_float);
        // This is a double
        double my_double = 22.5;
        System.out.println(my_double);
    }
}